CREATE TABLE NhanVien(MaNV INT IDENTITY(1,1) PRIMARY KEY,TenNV NVARCHAR(100) NOT NULL,SoDienThoai VARCHAR(15) UNIQUE,ChucVu NVARCHAR(50));
CREATE TABLE KhachHang(MaKH INT IDENTITY(1,1) PRIMARY KEY,TenKH NVARCHAR(100) NOT NULL,DienThoai VARCHAR(15) UNIQUE,DiemTichLuy INT NOT NULL DEFAULT 0);
CREATE TABLE SanPham(MaSP VARCHAR(20) PRIMARY KEY,TenSP NVARCHAR(150) NOT NULL,GiaBan DECIMAL(18,2) NOT NULL CHECK(GiaBan>0),SoLuongTon INT NOT NULL CHECK(SoLuongTon>=0));
CREATE TABLE HoaDon(MaHD INT IDENTITY(1,1) PRIMARY KEY,NgayLap DATETIME NOT NULL DEFAULT GETDATE(),MaNV INT NOT NULL,MaKH INT NULL,TongTien DECIMAL(18,2) NOT NULL,CONSTRAINT FK_HoaDon_NV FOREIGN KEY(MaNV) REFERENCES NhanVien(MaNV),CONSTRAINT FK_HoaDon_KH FOREIGN KEY(MaKH) REFERENCES KhachHang(MaKH));
CREATE TABLE ChiTietHoaDon(MaHD INT NOT NULL,MaSP VARCHAR(20) NOT NULL,SoLuong INT NOT NULL CHECK(SoLuong>0),DonGia DECIMAL(18,2) NOT NULL,PRIMARY KEY(MaHD,MaSP),FOREIGN KEY(MaHD) REFERENCES HoaDon(MaHD),FOREIGN KEY(MaSP) REFERENCES SanPham(MaSP));
